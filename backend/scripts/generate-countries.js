// Rebuilds the one country list the sign-up form (apps/mobile) and the API (backend) share:
// ISO 3166-1 alpha-2 code, English name and dial code ("+91") for every country, India first and
// then A-Z by name. Run it from backend/:
//
//   node scripts/generate-countries.js
//
// It writes the SAME list to two files, so the app and the server validate with identical data:
//   backend/src/common/constants/countries.js   (CommonJS, used by the API)
//   apps/mobile/src/data/countryList.js         (ES module, used by the app)
//
// Where the data comes from:
//   - which countries exist, and each one's dial code: libphonenumber-js (already a dependency
//     of both apps; the ITU calling codes in its metadata);
//   - the English names: Node's Intl.DisplayNames (CLDR). Hermes on phones does not support it
//     reliably, which is why the names are written into the file here instead of looked up at
//     runtime. Nothing in this script runs inside the app.
// Do not edit the generated files by hand: change this script and run it again.
const fs = require('fs');
const path = require('path');
const { getCountries, getCountryCallingCode } = require('libphonenumber-js');

const FIRST = 'IN'; // the app's home market is listed first

function buildCountries() {
  const names = new Intl.DisplayNames(['en'], { type: 'region' });
  const list = [];
  for (const code of getCountries()) {
    const name = names.of(code);
    // DisplayNames answers with the code itself for a region it does not know.
    if (!name || name === code) continue;
    list.push({ code, name, dial: `+${getCountryCallingCode(code)}` });
  }
  list.sort((a, b) => a.name.localeCompare(b.name, 'en'));
  const first = list.findIndex((c) => c.code === FIRST);
  return [list[first], ...list.slice(0, first), ...list.slice(first + 1)];
}

const HEADER = `// GENERATED by backend/scripts/generate-countries.js: do not edit by hand.
// ISO 3166-1 alpha-2 code, English name and dial code of every country, India first, then A-Z.
// The app and the API each hold a copy of this list; backend/tests/countries.test.js fails when
// the two differ.
`;

function render(list, esm) {
  const rows = list.map((c) => `  ${JSON.stringify(c)},`).join('\n');
  const body = `const COUNTRIES = [\n${rows}\n];\n`;
  return esm ? `${HEADER}export ${body}` : `${HEADER}${body}\nmodule.exports = { COUNTRIES };\n`;
}

const TARGETS = [
  { file: path.join(__dirname, '..', 'src', 'common', 'constants', 'countries.js'), esm: false },
  { file: path.join(__dirname, '..', '..', 'apps', 'mobile', 'src', 'data', 'countryList.js'), esm: true },
];

if (require.main === module) {
  const list = buildCountries();
  for (const { file, esm } of TARGETS) {
    fs.writeFileSync(file, render(list, esm));
    console.log(`wrote ${list.length} countries to ${path.relative(process.cwd(), file)}`);
  }
}

module.exports = { buildCountries, render };
