// Generates a tiny synthetic PDF for upload, clearly labeled as synthetic test data — never a real
// medical document. Uses pdf-lib, already a backend dependency (no new package needed).
const fs = require('fs');
const path = require('path');
const { PDFDocument, StandardFonts, rgb } = require('pdf-lib');

async function generateSyntheticPdf({ runId, outDir }) {
  const doc = await PDFDocument.create();
  const page = doc.addPage([420, 300]);
  const font = await doc.embedFont(StandardFonts.HelveticaBold);
  const body = await doc.embedFont(StandardFonts.Helvetica);

  page.drawText('SYNTHETIC TEST DOCUMENT', { x: 40, y: 250, size: 18, font, color: rgb(0.7, 0, 0) });
  page.drawText('NOT A REAL MEDICAL RECORD', { x: 40, y: 225, size: 12, font, color: rgb(0.7, 0, 0) });
  page.drawText(`Generated by the HumanCare Synthetic E2E Test Orchestrator`, { x: 40, y: 190, size: 10, font: body });
  page.drawText(`Run ID: ${runId}`, { x: 40, y: 170, size: 10, font: body });
  page.drawText(`Generated at: ${new Date().toISOString()}`, { x: 40, y: 152, size: 10, font: body });
  page.drawText('This file contains no real patient information.', { x: 40, y: 120, size: 10, font: body });

  const bytes = await doc.save();
  fs.mkdirSync(outDir, { recursive: true });
  const filePath = path.join(outDir, `synthetic-${runId}.pdf`);
  fs.writeFileSync(filePath, bytes);
  return filePath;
}

function removeSyntheticPdf(filePath) {
  try { fs.unlinkSync(filePath); } catch { /* best effort — not a database row, never audit evidence */ }
}

module.exports = { generateSyntheticPdf, removeSyntheticPdf };
